# Write the import table of a PE file as a C++ header for import_check.cpp.
# Usage: gen_table.py <exe> <out.h>
import re, subprocess, sys
out = subprocess.run(["llvm-objdump", "-p", sys.argv[1]], capture_output=True, text=True, check=True).stdout
dll = None
rows = []
for line in out.splitlines():
    m = re.match(r"\s*DLL Name: (\S+)", line)
    if m:
        dll = m.group(1)
        continue
    m = re.match(r"\s+\d+\s+(?:\d+\s+)?(\w+)$", line)
    if dll and m:
        rows.append((dll, m.group(1)))
with open(sys.argv[2], "w") as f:
    f.write("// Generated by gen_table.py\n#pragma once\nstatic const struct { const wchar_t* dll; const char* name; } g_imports[] = {\n")
    for d, n in rows:
        f.write('\t{L"%s", "%s"},\n' % (d, n))
    f.write("};\n")
print(len(rows), "imports")
