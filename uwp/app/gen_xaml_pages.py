#!/usr/bin/env python3
"""Embeds the XAML pages and item templates of uwp/app/xaml/ into a C++ include file.

  gen_xaml_pages.py <xaml dir> <output .inc>

Each xaml/<name>.xaml becomes `inline constexpr wchar_t k_xaml_<name>[] = LR"..."`, parsed at run
time by Windows.UI.Xaml.Markup.XamlReader (no XAML compiler involved).
"""

import os
import sys

DELIM = "__xaml__"


def main():
    src, out = sys.argv[1], sys.argv[2]
    lines = ["// Generated by uwp/app/gen_xaml_pages.py from uwp/app/xaml/*.xaml. Do not edit.", ""]
    for name in sorted(os.listdir(src)):
        if not name.endswith(".xaml"):
            continue
        with open(os.path.join(src, name), encoding="utf-8") as f:
            text = f.read()
        if f"){DELIM}\"" in text:
            raise SystemExit(f"{name} contains the raw string terminator")
        lines.append(f'inline constexpr wchar_t k_xaml_{name[:-5]}[] = LR"{DELIM}({text}){DELIM}";')
        lines.append("")
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
