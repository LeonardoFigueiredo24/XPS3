# Generate jump thunks for every Vulkan entry point declared in the given headers.
# Each vkXxx symbol jumps through uwp_vk_ptrs[i], which vkshim.cpp fills from the driver.
# Usage: gen_vkshim.py <out.c> <vulkan_core.h> [more headers...]
import re, sys

# Entry points implemented in vkshim.cpp itself (they load the driver first).
in_c = {"vkCreateInstance", "vkGetInstanceProcAddr", "vkEnumerateInstanceExtensionProperties",
        "vkEnumerateInstanceLayerProperties", "vkEnumerateInstanceVersion"}

names = []
for header in sys.argv[2:]:
    for m in re.finditer(r"VKAPI_ATTR\s+[\w\s\*]+?\s+VKAPI_CALL\s+(vk\w+)\s*\(", open(header).read()):
        if m.group(1) not in in_c and m.group(1) not in names:
            names.append(m.group(1))

with open(sys.argv[1], "w") as f:
    f.write("/* Generated by gen_vkshim.py */\n#include <stddef.h>\n\n")
    f.write("const char* const uwp_vk_names[] = {\n")
    for n in names:
        f.write('\t"%s",\n' % n)
    f.write("};\nconst size_t uwp_vk_count = %d;\nvoid* uwp_vk_ptrs[%d];\n\n" % (len(names), len(names)))
    f.write("__asm__(\".text\\n\"\n")
    for i, n in enumerate(names):
        f.write('\t".globl %s\\n%s: jmp *uwp_vk_ptrs+%d(%%rip)\\n"\n' % (n, n, 8 * i))
    f.write(");\n")
print(len(names), "thunks")
